// The Supabase dashboard's code editor is awkward with shared files, so this writes a
// single-file copy of the Stripe webhook with the payout helper (_shared/releasePayout.ts)
// pasted inside it. Paste the output into the dashboard instead of the real file.
//
//   node scripts/make-dashboard-webhook.cjs
//
// Output: supabase/functions/_dashboard/stripe-webhook.ts (a folder starting with "_"
// is never deployed as a function). The only import it still needs is
// ../_shared/rateLimit.ts, which the deployed function already has.
//
// Run it again whenever stripe-webhook/index.ts or _shared/releasePayout.ts changes.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "supabase", "functions");
const read = f => fs.readFileSync(path.join(root, f), "utf8").replace(/\r\n/g, "\n");

const webhook = read("stripe-webhook/index.ts");
let helper = read("_shared/releasePayout.ts");

// Only the release part: from the top up to the refund types, without the import
// (the webhook already imports createClient) and without "export".
const cut = helper.indexOf("export type RefundResult");
if (cut < 0) throw new Error("couldn't find where the refund code starts");
helper = helper.slice(0, cut)
  .replace(/^import \{ createClient \} from "https:\/\/esm\.sh\/@supabase\/supabase-js@2";\n\n?/, "")
  .replace(/^export (type|async function) /gm, "$1 ")
  .trimEnd();

const importLine = 'import { releasePayoutForApplication } from "../_shared/releasePayout.ts";\n';
if (!webhook.includes(importLine)) throw new Error("the webhook no longer imports releasePayout the way this script expects");

const header = [
  "// GENERATED by scripts/make-dashboard-webhook.cjs from stripe-webhook/index.ts and",
  "// _shared/releasePayout.ts, so it can be pasted into the dashboard as ONE file.",
  "// Do not edit it by hand; edit the real files and run the script again.",
  "",
].join("\n");

// The helper goes after the imports, before the first line of the webhook's own code.
const marker = "const stripe = new Stripe(";
const at = webhook.indexOf(marker);
if (at < 0) throw new Error("couldn't find where the webhook's own code starts");
const out = header + webhook.slice(0, at).replace(importLine, "") + "// ---- inlined from _shared/releasePayout.ts ----\n" + helper + "\n// ---- end of releasePayout ----\n\n" + webhook.slice(at);

const dir = path.join(root, "_dashboard");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "stripe-webhook.ts"), out);
console.log(`wrote supabase/functions/_dashboard/stripe-webhook.ts (${out.split("\n").length} lines)`);
