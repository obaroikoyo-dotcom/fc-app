// The Supabase dashboard's code editor is awkward with shared files (it is easy to paste
// one file's contents into another's), so this writes a single-file copy of the Stripe
// webhook with both shared helpers pasted inside it: the rate limiter
// (_shared/rateLimit.ts) and the payout helper (_shared/releasePayout.ts). The result
// has no imports of our own files, so nothing else in the dashboard matters.
//
//   node scripts/make-dashboard-webhook.cjs
//
// Output: supabase/functions/_dashboard/stripe-webhook.ts (a folder starting with "_"
// is never deployed as a function). Paste it over index.ts in the dashboard.
//
// Run it again whenever stripe-webhook/index.ts or the two shared files change.

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "supabase", "functions");
const read = f => fs.readFileSync(path.join(root, f), "utf8").replace(/\r\n/g, "\n");

const CREATE_CLIENT_IMPORT = /^import \{ createClient \} from "https:\/\/esm\.sh\/@supabase\/supabase-js@2";\n\n?/;

const webhook = read("stripe-webhook/index.ts");

// Rate limiter: everything, without its import and without "export".
const limiter = read("_shared/rateLimit.ts")
  .replace(CREATE_CLIENT_IMPORT, "")
  .replace(/^export (interface|async function|function) /gm, "$1 ")
  .trimEnd();

// Payout helper: only the release part (up to the refund types), same treatment.
let helper = read("_shared/releasePayout.ts");
const cut = helper.indexOf("export type RefundResult");
if (cut < 0) throw new Error("couldn't find where the refund code starts");
helper = helper.slice(0, cut)
  .replace(CREATE_CLIENT_IMPORT, "")
  .replace(/^export (type|async function) /gm, "$1 ")
  .trimEnd();

const limiterImport = 'import { checkRateLimit, clientIdentifier } from "../_shared/rateLimit.ts";\n';
const helperImport = 'import { releasePayoutForApplication } from "../_shared/releasePayout.ts";\n';
for (const line of [limiterImport, helperImport]) {
  if (!webhook.includes(line)) throw new Error(`the webhook no longer has the import this script expects: ${line.trim()}`);
}

const header = [
  "// GENERATED by scripts/make-dashboard-webhook.cjs from stripe-webhook/index.ts,",
  "// _shared/rateLimit.ts and _shared/releasePayout.ts, so it can be pasted into the dashboard",
  "// as ONE file with no other files. Do not edit it by hand; edit the real files and run the",
  "// script again.",
  "",
].join("\n");

const marker = "const stripe = new Stripe(";
const at = webhook.indexOf(marker);
if (at < 0) throw new Error("couldn't find where the webhook's own code starts");

const out =
  header +
  webhook.slice(0, at).replace(limiterImport, "").replace(helperImport, "") +
  "// ---- inlined from _shared/rateLimit.ts ----\n" + limiter + "\n// ---- end of rateLimit ----\n\n" +
  "// ---- inlined from _shared/releasePayout.ts ----\n" + helper + "\n// ---- end of releasePayout ----\n\n" +
  webhook.slice(at);

const dir = path.join(root, "_dashboard");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "stripe-webhook.ts"), out);
console.log(`wrote supabase/functions/_dashboard/stripe-webhook.ts (${out.split("\n").length} lines)`);
