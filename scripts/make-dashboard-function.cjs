// The Supabase dashboard's code editor is awkward with shared files (it is easy to paste
// one file's contents into another's, which crashes the function on start). This writes a
// single-file copy of an edge function with the shared helpers it imports pasted inside it,
// so the result needs no other file in the dashboard.
//
//   node scripts/make-dashboard-function.cjs <function-name>
//   e.g. node scripts/make-dashboard-function.cjs stripe-webhook
//
// Output: supabase/functions/_dashboard/<function-name>.ts (a folder starting with "_" is
// never deployed as a function). Paste it over index.ts in the dashboard.
//
// Handles imports of ../_shared/rateLimit.ts and ../_shared/releasePayout.ts (only the payout
// half of that one). Run it again whenever the function or a shared file changes.

const fs = require("fs");
const path = require("path");

const name = process.argv[2];
if (!name) {
  console.error("usage: node scripts/make-dashboard-function.cjs <function-name>");
  process.exit(2);
}

const root = path.join(__dirname, "..", "supabase", "functions");
const read = f => fs.readFileSync(path.join(root, f), "utf8").replace(/\r\n/g, "\n");

const CREATE_CLIENT_IMPORT = /^import \{ createClient \} from "https:\/\/esm\.sh\/@supabase\/supabase-js@2";\n\n?/;

// The shared files we know how to inline, and how to trim each one.
const SHARED = {
  rateLimit: () =>
    read("_shared/rateLimit.ts")
      .replace(CREATE_CLIENT_IMPORT, "")
      .replace(/^export (interface|async function|function) /gm, "$1 ")
      .trimEnd(),
  releasePayout: () => {
    const full = read("_shared/releasePayout.ts");
    const cut = full.indexOf("export type RefundResult");
    if (cut < 0) throw new Error("couldn't find where the refund code starts in releasePayout.ts");
    return full.slice(0, cut)
      .replace(CREATE_CLIENT_IMPORT, "")
      .replace(/^export (type|async function) /gm, "$1 ")
      .trimEnd();
  },
};

let source = read(`${name}/index.ts`);
const importRe = /^import \{[^}]*\} from "\.\.\/_shared\/(\w+)\.ts";\n/gm;
const inlined = [];
let match;
while ((match = importRe.exec(source))) {
  const module = match[1];
  if (!SHARED[module]) throw new Error(`${name} imports _shared/${module}.ts, which this script doesn't know how to inline yet`);
  inlined.push({ module, line: match[0] });
}
if (inlined.length === 0) console.log(`(${name} imports no shared files; copied as it is)`);

const marker = source.search(/^(const|let|serve|async function|function) /m);
if (marker < 0) throw new Error("couldn't find where the function's own code starts");
// the first non-import statement; imports are everything above it
let head = source.slice(0, marker), body = source.slice(marker);
for (const { line } of inlined) head = head.replace(line, "");
const blocks = inlined.map(({ module }) => `// ---- inlined from _shared/${module}.ts ----\n${SHARED[module]()}\n// ---- end of ${module} ----\n\n`).join("");

const header = [
  `// GENERATED by scripts/make-dashboard-function.cjs from ${name}/index.ts${inlined.length ? " and " + inlined.map(i => `_shared/${i.module}.ts`).join(", ") : ""},`,
  "// so it can be pasted into the dashboard as ONE file with no other files. Do not edit it by",
  "// hand; edit the real files and run the script again.",
  "",
].join("\n");

const out = header + head.replace(/\n+$/, "\n") + "\n" + blocks + body;
const dir = path.join(root, "_dashboard");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, `${name}.ts`), out);
console.log(`wrote supabase/functions/_dashboard/${name}.ts (${out.split("\n").length} lines)`);
